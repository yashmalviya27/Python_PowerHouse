# in this i create a class and create 2 object of it
class student:
    def __init__(self, name, age, marks):
        self.name = name
        self.age = age
        self.marks = marks
    
    def display(self):
        print(f"Name: {self.name}\nAge: {self.age}\nMarks: {self.marks}")
# create 1 object of class 
s1 = student("Yash", 20, 80)
s1.display()

print("-----------------")
# create 2 object of class
s2 = student("Raj", 30, 80)
s2.display()
